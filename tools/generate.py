"""Generate models and endpoint methods from the Jellyfin OpenAPI spec.

Usage: python tools/generate.py [path/to/jellyfin-openapi.json]

Only the constructs the Jellyfin spec actually uses are supported; anything
else raises, so a spec change surfaces here instead of producing wrong types.
"""

from __future__ import annotations

import json
import keyword
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

import unasync

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SPEC = ROOT / "spec" / "jellyfin-openapi.json"
PACKAGE = ROOT / "src" / "jellyfin_client"
OUT = PACKAGE / "generated"

# Names that differ between the async source and the generated sync code.
# unasync already drops async/await and maps async context managers/iterators.
SYNC_REPLACEMENTS = {
    "_async": "_sync",
    "asyncio": "time",
    "AsyncConnectCallback": "SyncConnectCallback",
    "AsyncGeneratedApi": "GeneratedApi",
    "AsyncJellyfinClient": "JellyfinClient",
    "AsyncJellyfinWebSocket": "JellyfinWebSocket",
    "AsyncRemoteControl": "RemoteControl",
    "AsyncStreamResponse": "SyncStreamResponse",
    "AsyncTransport": "SyncTransport",
    "AsyncWebSocket": "SyncWebSocket",
    "async_connect_to_address": "connect_to_address",
}

PRIMITIVES = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}

# Request bodies other than JSON: media type -> (encoding, default Content-Type).
# The spec declares image uploads as binary, but the server decodes them as
# base64 (GetFromBase64Stream in Jellyfin.Api/Controllers/ImageController.cs).
BODY_ENCODINGS = {
    "image/*": ("base64", "image/jpeg"),
    "text/plain": ("text", "text/plain"),
}

HEADER = "# Generated by tools/generate.py from the Jellyfin OpenAPI spec {version}. Do not edit.\n"


def snake(name: str) -> str:
    """Convert camelCase/PascalCase to snake_case."""
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower()
    return f"{name}_" if keyword.iskeyword(name) else name


def docstring(text: str) -> str:
    return text.strip().replace("\\", "\\\\").replace('"""', "'''")


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[1]


class TypeMapper:
    """Map OpenAPI schemas to Python type expressions."""

    def __init__(self, schemas: dict[str, Any], prefix: str = "") -> None:
        self.schemas = schemas
        self.prefix = prefix

    def __call__(self, schema: dict[str, Any]) -> str:
        nullable = schema.get("nullable", False)
        expr = self._base(schema)
        if nullable and expr != "Any":
            expr = f"{expr} | None"
        return expr

    def _base(self, schema: dict[str, Any]) -> str:
        if "$ref" in schema:
            return self.prefix + ref_name(schema["$ref"])
        if "allOf" in schema:
            # Jellyfin wraps a single $ref in allOf to attach nullable/description.
            (inner,) = schema["allOf"]
            return self._base(inner)
        if "oneOf" in schema:
            return " | ".join(self._base(s) for s in schema["oneOf"])
        kind = schema.get("type")
        if kind is None:
            return "Any"
        if kind in PRIMITIVES:
            return PRIMITIVES[kind]
        if kind == "array":
            return f"list[{self(schema['items'])}]"
        if kind == "object":
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict):
                return f"dict[str, {self(extra)}]"
            return "dict[str, Any]"
        raise ValueError(f"Unsupported schema: {schema}")


def render_models(spec: dict[str, Any]) -> str:
    schemas = spec["components"]["schemas"]
    to_type = TypeMapper(schemas)
    lines = [
        HEADER.format(version=spec["info"]["version"]),
        '"""Jellyfin API models.',
        "",
        "TypedDicts describe the JSON as received; nothing is validated at runtime,",
        "so new fields and enum values from newer servers pass through unchanged.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Literal, NotRequired, TypedDict",
        "",
    ]
    for name, schema in schemas.items():
        doc = docstring(schema.get("description", ""))
        if "enum" in schema:
            values = ", ".join(json.dumps(v) for v in schema["enum"])
            lines += ["", f"type {name} = Literal[{values}]"]
            if doc:
                lines.append(f'"""{doc}"""')
            continue
        if "oneOf" in schema:
            lines += ["", f"type {name} = {to_type(schema)}"]
            continue
        props = schema.get("properties", {})
        if schema.get("type") != "object":
            raise ValueError(f"Unsupported top-level schema {name}: {schema}")
        required = set(schema.get("required", []))
        lines += ["", "", f"class {name}(TypedDict):"]
        lines.append(f'    """{doc or name}"""')
        lines.append("")
        for prop, prop_schema in props.items():
            expr = to_type(prop_schema)
            if prop not in required:
                expr = f"NotRequired[{expr}]"
            lines.append(f"    {prop}: {expr}")
    return "\n".join(lines) + "\n"


def classify(op: dict[str, Any], http_method: str) -> tuple[str, dict[str, Any] | None]:
    """Return how to expose an operation: ("json"|"none"|"url", schema) or ("skip", reason)."""
    body = op.get("requestBody", {}).get("content")
    if body and "application/json" not in body and not BODY_ENCODINGS.keys() & body.keys():
        return ("skip", {"reason": f"unsupported request body {sorted(body)}"})
    responses = op["responses"]
    if "204" in responses:
        return ("none", None)
    ok = responses.get("200")
    if ok is None:
        return ("skip", {"reason": "no 200 or 204 response"})
    content = ok.get("content")
    if not content:
        return ("none", None)
    if "application/json" in content:
        return ("json", content["application/json"]["schema"])
    if http_method == "get":
        return ("url", None)
    return ("skip", {"reason": f"{http_method.upper()} returning {sorted(content)}"})


class Signature:
    """Python parameters of an operation and how they map to the request."""

    def __init__(self, op: dict[str, Any], to_type: TypeMapper) -> None:
        params = [p for p in op.get("parameters", []) if p["in"] in ("path", "query")]
        self.path_params = [p for p in params if p["in"] == "path"]
        self.query_params = [p for p in params if p["in"] == "query"]
        body_content = op.get("requestBody", {}).get("content", {})
        self.body = body_content.get("application/json")
        self.body_required = bool(op.get("requestBody", {}).get("required"))
        # (encoding, default Content-Type) for a raw upload body, else None.
        self.upload = next(
            (BODY_ENCODINGS[media] for media in body_content if media in BODY_ENCODINGS), None
        )
        self.to_type = to_type

    def args(self, extra: list[str] | None = None) -> list[str]:
        args = ["self"]
        for p in self.path_params:
            args.append(f"{snake(p['name'])}: {self.to_type(p['schema'])}")
        keyword_args: list[str] = []
        if self.upload:
            encoding, _ = self.upload
            keyword_args.append("body: bytes" if encoding == "base64" else "body: str | bytes")
        if self.body:
            body_type = self.to_type(self.body["schema"])
            keyword_args.append(
                f"body: {body_type}" if self.body_required else f"body: {body_type} | None = None"
            )
        for p in self.query_params:
            if p.get("required"):
                keyword_args.append(f"{snake(p['name'])}: {self.to_type(p['schema'])}")
        for p in self.query_params:
            if not p.get("required"):
                expr = self.to_type(p["schema"])
                if not expr.endswith("| None"):
                    expr += " | None"
                keyword_args.append(f"{snake(p['name'])}: {expr} = None")
        if self.upload:
            keyword_args.append(f'content_type: str = "{self.upload[1]}"')
        keyword_args.extend(extra or [])
        if keyword_args:
            args.append("*")
        return args + keyword_args

    def path_expr(self, path: str) -> str:
        if not self.path_params:
            return f'"{path}"'
        for p in self.path_params:
            path = path.replace("{" + p["name"] + "}", "{_quote(" + snake(p["name"]) + ")}")
        return f'f"{path}"'

    def params_expr(self) -> str:
        mapping = ", ".join(f'"{p["name"]}": {snake(p["name"])}' for p in self.query_params)
        return f"{{{mapping}}}"


def render_method(
    path: str, http_method: str, op: dict[str, Any], sig: Signature, returns: str
) -> str:
    call = [f'"{http_method.upper()}"', sig.path_expr(path)]
    if sig.query_params:
        call.append(f"params={sig.params_expr()}")
    if sig.body:
        call.append("json=body")
    if sig.upload:
        encoding, _ = sig.upload
        content = "base64.b64encode(body)" if encoding == "base64" else "_to_bytes(body)"
        call.append(f"content={content}, content_type=content_type")
    request = f"await self._request({', '.join(call)})"
    if returns != "None":
        request = f'return cast("{returns}", {request})'
    summary = docstring(op.get("summary") or op["operationId"])
    note = ""
    if sig.upload and sig.upload[0] == "base64":
        note = "        Pass the raw bytes; they are sent base64-encoded as the server expects.\n"
    return (
        f"    async def {snake(op['operationId'])}({', '.join(sig.args())}) -> {returns}:\n"
        f'        """{summary}\n\n'
        f"        {http_method.upper()} {path}\n"
        f"{note}"
        f'        """\n'
        f"        {request}\n"
    )


def render_url_builder(path: str, op: dict[str, Any], sig: Signature) -> str:
    summary = docstring(op.get("summary") or op["operationId"])
    args = sig.args(["include_token: bool = True"])
    params = sig.params_expr() if sig.query_params else "{}"
    build = f"self.build_url({sig.path_expr(path)}, {params}, include_token=include_token)"
    return (
        f"    def {snake(op['operationId'])}_url({', '.join(args)}) -> str:\n"
        f'        """URL: {summary}\n\n'
        f"        GET {path}\n"
        f'        """\n'
        f"        return {build}\n"
    )


def render_endpoints(spec: dict[str, Any]) -> tuple[str, str, dict[str, int], list[str]]:
    """Render the async endpoint class and the URL builder class.

    Returns both sources, counts per kind and the skipped operations.
    """
    to_type = TypeMapper(spec["components"]["schemas"], prefix="models.")
    methods: list[str] = []
    url_builders: list[str] = []
    skipped: list[str] = []
    for path, item in spec["paths"].items():
        for http_method, op in item.items():
            if op.get("deprecated"):
                continue
            kind, schema = classify(op, http_method)
            if kind == "skip":
                assert schema is not None
                skipped.append(f"{http_method.upper()} {path}: {schema['reason']}")
                continue
            sig = Signature(op, to_type)
            if kind == "url":
                url_builders.append(render_url_builder(path, op, sig))
            else:
                returns = "None" if kind == "none" else to_type(schema or {})
                methods.append(render_method(path, http_method, op, sig, returns))
    version = spec["info"]["version"]
    quote_helper = [
        "",
        "",
        "def _quote(value: object) -> str:",
        '    return quote(str(value), safe="")',
        "",
        "",
    ]
    endpoints = "\n".join(
        [
            HEADER.format(version=version),
            '"""Jellyfin API endpoint methods."""',
            "",
            "import base64",
            "from typing import Any, cast",
            "from urllib.parse import quote",
            "",
            "from .. import models",
            *quote_helper,
            "def _to_bytes(body: str | bytes) -> bytes:",
            "    return body.encode() if isinstance(body, str) else body",
            "",
            "",
            "class AsyncGeneratedApi:",
            '    """Endpoint methods; subclasses provide the transport."""',
            "",
            "    async def _request(",
            "        self,",
            "        method: str,",
            "        path: str,",
            "        *,",
            "        params: dict[str, Any] | None = None,",
            "        json: Any = None,",
            "        content: bytes | None = None,",
            "        content_type: str | None = None,",
            "    ) -> Any:",
            "        raise NotImplementedError",
            "",
            *methods,
        ]
    )
    urls = "\n".join(
        [
            HEADER.format(version=version),
            '"""URLs for endpoints returning images, streams or files.',
            "",
            "These are handed to players or fetched by the caller; building them",
            "needs no I/O, so both stacks share them.",
            '"""',
            "",
            "from collections.abc import Mapping",
            "from typing import Any",
            "from urllib.parse import quote",
            "",
            "from . import models",
            *quote_helper,
            "class GeneratedUrls:",
            '    """URL builders; subclasses provide build_url()."""',
            "",
            "    def build_url(",
            "        self, path: str, params: Mapping[str, Any], *, include_token: bool",
            "    ) -> str:",
            "        raise NotImplementedError",
            "",
            *url_builders,
        ]
    )
    counts = {"methods": len(methods), "url builders": len(url_builders), "skipped": len(skipped)}
    return endpoints, urls, counts, skipped


def generate_sync(async_dirs: list[Path]) -> list[Path]:
    """Write the sync stack next to each async source directory."""
    sources = [str(f) for d in async_dirs for f in sorted(d.glob("*.py"))]
    rule = unasync.Rule("/_async/", "/_sync/", additional_replacements=SYNC_REPLACEMENTS)
    unasync.unasync_files(sources, [rule])
    sync_dirs = [d.parent / "_sync" for d in async_dirs]
    for sync_dir in sync_dirs:
        for path in sync_dir.glob("*.py"):
            header = f"# Generated by tools/generate.py from _async/{path.name}. Do not edit.\n"
            path.write_text(header + path.read_text())
    return sync_dirs


def main() -> None:
    spec_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SPEC
    spec = json.loads(spec_path.read_text())
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "__init__.py").write_text(
        HEADER.format(version=spec["info"]["version"])
        + f'"""Generated code."""\n\nSPEC_VERSION = "{spec["info"]["version"]}"\n'
    )
    (OUT / "models.py").write_text(render_models(spec))
    endpoints, urls, counts, skipped = render_endpoints(spec)
    (OUT / "urls.py").write_text(urls)
    (OUT / "_async").mkdir(exist_ok=True)
    (OUT / "_async" / "__init__.py").write_text('"""Generated async endpoint methods."""\n')
    (OUT / "_async" / "endpoints.py").write_text(endpoints)
    sync_dirs = generate_sync([PACKAGE / "_async", OUT / "_async"])
    sync_paths = [str(d) for d in sync_dirs]
    subprocess.run(["ruff", "check", "--quiet", "--fix", "--select", "I", *sync_paths], check=True)
    subprocess.run(["ruff", "format", "--quiet", str(OUT), *sync_paths], check=True)
    models_count = len(spec["components"]["schemas"])
    summary = ", ".join(f"{n} {kind}" for kind, n in counts.items())
    print(f"spec {spec['info']['version']}: {models_count} models, {summary}")
    for line in skipped:
        print(f"  skipped {line}")


if __name__ == "__main__":
    main()
